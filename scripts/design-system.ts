/**
 * Mukhtalif design-system tooling for the public website.
 *
 *   pnpm design:build     regenerate every output from libs/design-tokens/src/web.ts
 *   pnpm design:check     fail when outputs drift, a token name is unknown, or a
 *                         file gains hard-coded design values beyond its baseline
 *   pnpm design:baseline  record the current hard-coded counts (owner-approved only)
 *
 * The guard is a ratchet: existing debt is recorded per file in
 * design-system/guard-baseline.json and may only go down. A new CSS file starts
 * at zero, so it must use tokens throughout.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import {
  brandColor,
  broadcastColor,
  utilityColor,
  webBreakpoints,
  webColor,
  webFont,
  webLayout,
  webLeading,
  webMotion,
  webRadius,
  webSpace,
  webText,
  webWeight,
  type ScaleToken,
  type ThemedToken,
} from '../libs/design-tokens/src/web';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const paths = {
  tokensCss: join(root, 'apps/web/src/app/tokens.css'),
  errorCss: join(root, 'apps/web/public/error-state.css'),
  tokensDoc: join(root, 'design-system/TOKENS.md'),
  baseline: join(root, 'design-system/guard-baseline.json'),
  webSrc: join(root, 'apps/web/src'),
  webPublic: join(root, 'apps/web/public'),
};

const kebab = (key: string) => key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

interface Row {
  name: string;
  light: string;
  dark: string;
  label: string;
  role: string;
}

function themed(prefix: string, tokens: Record<string, ThemedToken>): Row[] {
  return Object.entries(tokens).map(([key, t]) => ({
    name: `--mk-${prefix}${kebab(key)}`,
    light: t.light,
    dark: t.dark,
    label: t.label,
    role: t.role,
  }));
}

function scale(prefix: string, tokens: Record<string, ScaleToken>): Row[] {
  return Object.entries(tokens).map(([key, t]) => ({
    name: `--mk-${prefix}${kebab(key)}`,
    light: t.value,
    dark: t.value,
    label: t.label,
    role: t.role,
  }));
}

const sections: { title: string; rows: Row[] }[] = [
  { title: 'Colour: roles', rows: themed('', webColor) },
  { title: 'Colour: brand', rows: themed('', brandColor) },
  { title: 'Colour: broadcast (player)', rows: themed('', broadcastColor) },
  { title: 'Colour: feedback and overlays', rows: themed('', utilityColor) },
  { title: 'Type: family', rows: [{ ...scale('', webFont)[0], name: '--mk-font' }] },
  { title: 'Type: weight', rows: scale('weight-', webWeight) },
  { title: 'Type: size', rows: scale('text-', webText) },
  { title: 'Type: line height', rows: scale('leading-', webLeading) },
  { title: 'Spacing', rows: scale('space-', webSpace) },
  { title: 'Radius', rows: themed('radius-', webRadius) },
  { title: 'Layout', rows: themed('', webLayout) },
  { title: 'Motion', rows: scale('duration-', webMotion) },
];

const allRows = sections.flatMap((s) => s.rows);
const tokenNames = new Set(allRows.map((r) => r.name));

// ---------------------------------------------------------------- outputs

const generatedNote =
  'GENERATED by `pnpm design:build` from libs/design-tokens/src/web.ts. Do not edit.';

function tokensCss(): string {
  const light: string[] = [];
  const dark: string[] = [];
  for (const section of sections) {
    light.push(`  /* ${section.title} */`);
    for (const row of section.rows) light.push(`  ${row.name}: ${row.light};`);
    const changed = section.rows.filter((row) => row.dark !== row.light);
    if (changed.length) {
      dark.push(`  /* ${section.title} */`);
      for (const row of changed) dark.push(`  ${row.name}: ${row.dark};`);
    }
  }
  return [
    `/* ${generatedNote} */`,
    '',
    ':root {',
    ...light,
    '}',
    '',
    '/* The warm green-black appearance. Only tokens that differ are repeated. */',
    ":root[data-concept='third'] {",
    ...dark,
    '}',
    '',
  ].join('\n');
}

/** The standalone error page cannot load tokens.css, so its palette is written in place. */
function errorPalette(theme: 'light' | 'dark'): string {
  const pick = (t: ThemedToken) => t[theme];
  return [
    `--bg: ${pick(webColor.page)};`,
    `--fg: ${pick(webColor.ink)};`,
    `--muted: ${pick(webColor.inkMuted)};`,
    `--surface: ${pick(webColor.surface)};`,
  ].join('\n');
}

function replaceRegion(
  text: string,
  start: string,
  end: string,
  body: string,
  indent: string,
): string {
  const pattern = new RegExp(`(${escape(start)})[\\s\\S]*?(\\n[ \\t]*${escape(end)})`);
  if (!pattern.test(text)) throw new Error(`Missing generated region ${start} … ${end}`);
  const lines = body.split('\n').map((line) => (line ? indent + line : line));
  return text.replace(pattern, (_m, a: string, b: string) => `${a}\n${lines.join('\n')}${b}`);
}

const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

function errorCss(current: string): string {
  let next = replaceRegion(
    current,
    '/* mk:light:start */',
    '/* mk:light:end */',
    errorPalette('light'),
    '  ',
  );
  next = replaceRegion(
    next,
    '/* mk:dark:start */',
    '/* mk:dark:end */',
    errorPalette('dark'),
    '    ',
  );
  return next;
}

function tokensDoc(current: string): string {
  const cell = (value: string) => value.replace(/\|/g, '\\|');
  const parts: string[] = [`<!-- ${generatedNote} -->`, ''];
  for (const section of sections) {
    parts.push(`### ${section.title}`, '');
    const themedSection = section.rows.some((r) => r.dark !== r.light);
    if (themedSection) {
      parts.push(
        '| Token | Light | Dark | Arabic name | Role |',
        '| --- | --- | --- | --- | --- |',
      );
      for (const r of section.rows) {
        parts.push(
          `| \`${r.name}\` | \`${cell(r.light)}\` | ${r.dark === r.light ? 'same' : `\`${cell(r.dark)}\``} | ${r.label} | ${cell(r.role)} |`,
        );
      }
    } else {
      parts.push('| Token | Value | Arabic name | Role |', '| --- | --- | --- | --- |');
      for (const r of section.rows) {
        parts.push(`| \`${r.name}\` | \`${cell(r.light)}\` | ${r.label} | ${cell(r.role)} |`);
      }
    }
    parts.push('');
  }
  parts.push(
    '### Breakpoints',
    '',
    '| Name | Width | Use |',
    '| --- | --- | --- |',
    ...Object.entries(webBreakpoints).map(([k, v]) => `| ${k} | \`${v.value}\` | ${v.role} |`),
    '',
  );
  return replaceRegion(
    current,
    '<!-- mk:tokens:start -->',
    '<!-- mk:tokens:end -->',
    parts.join('\n'),
    '',
  );
}

/** Outputs are formatted with the repository's Prettier config so `pnpm format` never drifts them. */
async function outputs(): Promise<{ path: string; content: string }[]> {
  const raw = [
    { path: paths.tokensCss, content: tokensCss() },
    { path: paths.errorCss, content: errorCss(readFileSync(paths.errorCss, 'utf8')) },
    { path: paths.tokensDoc, content: tokensDoc(readFileSync(paths.tokensDoc, 'utf8')) },
  ];
  return Promise.all(
    raw.map(async (output) => ({
      path: output.path,
      content: await prettier.format(output.content, {
        ...(await prettier.resolveConfig(output.path)),
        filepath: output.path,
      }),
    })),
  );
}

// ---------------------------------------------------------------- guard

type Category =
  | 'raw-color'
  | 'font-family'
  | 'font-size'
  | 'font-weight'
  | 'line-height'
  | 'radius'
  | 'spacing'
  | 'shadow'
  | 'hover-motion'
  | 'media-width'
  | 'important'
  | 'font-face-var';

const categoryHelp: Record<Category, string> = {
  'raw-color': 'Use a colour token (var(--mk-…)) or a legacy alias; never a hex/rgb/named colour.',
  'font-family': 'Use var(--font) / var(--mk-font); the site has one family.',
  'font-size': 'Use a type step var(--mk-text-…); display clamps need an owner decision.',
  'font-weight': 'Use var(--mk-weight-…).',
  'line-height': 'Use var(--mk-leading-…).',
  radius: 'Use var(--mk-radius-…) or the card alias var(--radius-card).',
  spacing: 'Use a spacing step var(--mk-space-…) or the gutter.',
  shadow: 'Shadows are not part of this system (DECISIONS.md D-07).',
  'hover-motion': 'Controls never move or scale on hover; change colour or fill instead.',
  'media-width': `Use a canonical width: ${Object.values(webBreakpoints)
    .map((b) => b.value)
    .join(', ')} (min-width may add 1px).`,
  important: 'Avoid !important; fix the cascade instead.',
  'font-face-var': '@font-face descriptors cannot read custom properties; write the literal value.',
};

const namedColors =
  /(^|[\s,(])(white|black|red|green|blue|gray|grey|silver|navy|maroon|purple|orange|yellow|pink|teal|olive|lime|aqua|fuchsia)(?=$|[\s,);])/i;
const colorProps = /(^|-)(color|background|border|outline|fill|stroke|shadow|decoration)/;
const canonicalWidths = new Set(Object.values(webBreakpoints).map((b) => parseInt(b.value, 10)));

interface Hit {
  category: Category;
  line: number;
  text: string;
}

function blankComments(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
}

function blankGenerated(text: string): string {
  return text.replace(/\/\* mk:(light|dark):start \*\/[\s\S]*?\/\* mk:\1:end \*\//g, (m) =>
    m.replace(/[^\n]/g, ' '),
  );
}

function scanCss(source: string): Hit[] {
  const text = blankComments(blankGenerated(source));
  const hits: Hit[] = [];
  const lineOf = (index: number) => text.slice(0, index).split('\n').length;
  const stack: string[] = [];
  const block = /([^{};]*)\{|\}|([^{};]+);/g;
  let m: RegExpExecArray | null;
  while ((m = block.exec(text))) {
    if (m[0].endsWith('{')) {
      const selector = m[1].trim();
      stack.push(selector);
      const media = selector.match(/^@media\b(.*)$/);
      if (media) {
        for (const w of media[1].matchAll(/(min|max)-width:\s*(\d+)px/g)) {
          const value = Number(w[2]);
          const ok =
            canonicalWidths.has(value) || (w[1] === 'min' && canonicalWidths.has(value - 1));
          if (!ok)
            hits.push({
              category: 'media-width',
              line: lineOf(m.index + m[0].indexOf('@')),
              text: selector,
            });
        }
      }
      continue;
    }
    if (m[0] === '}') {
      stack.pop();
      continue;
    }
    const decl = m[2].trim();
    if (stack.some((s) => s.startsWith('@font-face'))) {
      if (decl.includes('var(')) {
        hits.push({
          category: 'font-face-var',
          line: lineOf(m.index),
          text: decl.replace(/\s+/g, ' '),
        });
      }
      continue;
    }
    const colon = decl.indexOf(':');
    if (colon < 1) continue;
    const prop = decl.slice(0, colon).trim().toLowerCase();
    const value = decl.slice(colon + 1).trim();
    const line = lineOf(m.index + m[0].length - m[2].length + m[2].indexOf(decl));
    const add = (category: Category) =>
      hits.push({ category, line, text: decl.replace(/\s+/g, ' ') });
    const literal = value.replace(/var\([^()]*(\([^()]*\))*[^()]*\)/g, 'VAR');

    if (value.includes('!important')) add('important');
    if (
      /#[0-9a-f]{3,8}\b/i.test(literal) ||
      /\b(rgba?|hsla?|hwb|lab|lch|oklch|oklab)\(/i.test(literal)
    ) {
      add('raw-color');
    } else if (
      (prop.startsWith('--') || colorProps.test(prop)) &&
      namedColors.test(` ${literal}`)
    ) {
      add('raw-color');
    }
    if (prop === 'font-family' && !/^(var\(|inherit$)/.test(value)) add('font-family');
    if (prop === 'font' && !/^(inherit|var\()/.test(value)) add('font-family');
    if (prop === 'font-size' && /\d(px|rem|em)\b/.test(literal)) add('font-size');
    if (prop === 'font-weight' && /^\d+$|^bold$/.test(literal.trim())) add('font-weight');
    if (
      prop === 'line-height' &&
      /^\d+(\.\d+)?$/.test(literal.trim()) &&
      literal.trim() !== '1' &&
      literal.trim() !== '0'
    )
      add('line-height');
    if (/^border(-[a-z]+)*-radius$/.test(prop) && /\d(px|%)/.test(literal)) add('radius');
    if (
      /^(margin|padding|gap|row-gap|column-gap)(-|$)/.test(prop) &&
      /(^|[^\w.-])[1-9]\d*(\.\d+)?px/.test(literal)
    )
      add('spacing');
    if (/^(box-shadow|text-shadow)$/.test(prop) && literal !== 'none') add('shadow');
    if (prop === 'filter' && /drop-shadow/.test(literal)) add('shadow');
    if (
      prop === 'transform' &&
      /translate|scale/.test(literal) &&
      stack.length &&
      /:hover/.test(stack[stack.length - 1])
    )
      add('hover-motion');
  }
  return hits;
}

function scanTsx(source: string): Hit[] {
  const hits: Hit[] = [];
  source.split('\n').forEach((text, i) => {
    if (
      /#[0-9a-f]{6}\b|#[0-9a-f]{3}\b(?![\w-])/i.test(text) &&
      /['"`]/.test(text) &&
      !/href|#t=|#main|#team/.test(text)
    ) {
      hits.push({ category: 'raw-color', line: i + 1, text: text.trim() });
    }
  });
  return hits;
}

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (name === 'node_modules' || name.startsWith('.')) continue;
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

function scannedFiles(): string[] {
  const css = [
    ...walk(paths.webSrc),
    ...readdirSync(paths.webPublic).map((n) => join(paths.webPublic, n)),
  ].filter((f) => f.endsWith('.css') && f !== paths.tokensCss);
  const tsx = walk(paths.webSrc).filter((f) => /\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f));
  return [...css, ...tsx].sort();
}

function scanAll(): Map<string, Hit[]> {
  const result = new Map<string, Hit[]>();
  for (const file of scannedFiles()) {
    const source = readFileSync(file, 'utf8');
    result.set(relative(root, file), file.endsWith('.css') ? scanCss(source) : scanTsx(source));
  }
  return result;
}

type Counts = Record<string, Partial<Record<Category, number>>>;

function count(hits: Map<string, Hit[]>): Counts {
  const counts: Counts = {};
  for (const [file, list] of hits) {
    for (const hit of list) {
      counts[file] ??= {};
      counts[file][hit.category] = (counts[file][hit.category] ?? 0) + 1;
    }
  }
  return counts;
}

function unknownTokens(): string[] {
  const problems: string[] = [];
  for (const file of scannedFiles()) {
    const source = readFileSync(file, 'utf8');
    for (const m of source.matchAll(/var\(\s*(--mk-[a-z0-9-]+)(\$\{)?/g)) {
      // A name completed by a template expression is built from the token source itself.
      if (!m[2] && !tokenNames.has(m[1])) {
        const line = source.slice(0, m.index).split('\n').length;
        problems.push(`${relative(root, file)}:${line} unknown token ${m[1]}`);
      }
    }
  }
  return problems;
}

// ---------------------------------------------------------------- commands

async function build() {
  for (const output of await outputs()) {
    const before = existsSync(output.path) ? readFileSync(output.path, 'utf8') : '';
    if (before !== output.content) {
      writeFileSync(output.path, output.content);
      console.log(`wrote ${relative(root, output.path)}`);
    } else {
      console.log(`unchanged ${relative(root, output.path)}`);
    }
  }
}

async function check(): Promise<number> {
  let failures = 0;
  for (const output of await outputs()) {
    const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : '';
    if (current !== output.content) {
      console.error(`✗ ${relative(root, output.path)} is out of date. Run \`pnpm design:build\`.`);
      failures++;
    }
  }
  for (const problem of unknownTokens()) {
    console.error(`✗ ${problem}`);
    failures++;
  }
  const baseline: Counts = existsSync(paths.baseline)
    ? JSON.parse(readFileSync(paths.baseline, 'utf8'))
    : {};
  const hits = scanAll();
  const counts = count(hits);
  const improved: string[] = [];
  for (const [file, perCategory] of Object.entries(counts)) {
    for (const [category, n] of Object.entries(perCategory) as [Category, number][]) {
      const allowed = baseline[file]?.[category] ?? 0;
      if (n > allowed) {
        failures++;
        console.error(
          `✗ ${file}: ${category} ${n} > baseline ${allowed}. ${categoryHelp[category]}`,
        );
        for (const hit of hits.get(file)!.filter((h) => h.category === category)) {
          console.error(`    ${file}:${hit.line}  ${hit.text}`);
        }
      }
    }
  }
  for (const [file, perCategory] of Object.entries(baseline)) {
    for (const [category, allowed] of Object.entries(perCategory) as [Category, number][]) {
      const n = counts[file]?.[category] ?? 0;
      if (n < allowed) improved.push(`${file}: ${category} ${allowed} → ${n}`);
    }
  }
  if (improved.length) {
    console.log('Debt went down (run `pnpm design:baseline` to lock it in):');
    for (const line of improved) console.log(`  ${line}`);
  }
  const total = Object.values(counts).reduce(
    (sum, per) => sum + Object.values(per).reduce((a, b) => a + (b ?? 0), 0),
    0,
  );
  if (failures) {
    console.error(`design:check failed with ${failures} problem(s).`);
  } else {
    console.log(
      `design:check passed. ${tokenNames.size} tokens; ${total} recorded legacy values remain as tracked debt.`,
    );
  }
  return failures ? 1 : 0;
}

function writeBaseline() {
  const counts = count(scanAll());
  const sorted = Object.fromEntries(
    Object.keys(counts)
      .sort()
      .map((file) => [file, Object.fromEntries(Object.entries(counts[file]).sort())]),
  );
  writeFileSync(paths.baseline, `${JSON.stringify(sorted, null, 2)}\n`);
  console.log(`wrote ${relative(root, paths.baseline)}`);
}

async function main() {
  const command = process.argv[2];
  if (command === 'build') await build();
  else if (command === 'check') process.exitCode = await check();
  else if (command === 'baseline') writeBaseline();
  else {
    console.error('Usage: tsx scripts/design-system.ts <build|check|baseline>');
    process.exitCode = 2;
  }
}

void main();
