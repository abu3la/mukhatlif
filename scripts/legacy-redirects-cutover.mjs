/**
 * Writes the reviewed redirect changes that let every old WordPress address keep
 * working after mukhtalif.net moves to the new site.
 *
 *   node scripts/legacy-redirects-cutover.mjs > apps/api/supabase/legacy-redirects-cutover.sql
 *
 * Source paths are produced exactly the way the site looks them up (WHATWG path
 * encoding, upper-case escapes, one trailing slash), so a row always matches.
 * The audit behind every line is in docs/ROOT_CUTOVER.md.
 */

const sourcePath = (path) => {
  const encoded = new URL(path, 'https://legacy-path.invalid').pathname.replace(
    /%[0-9a-f]{2}/gi,
    (token) => token.toUpperCase(),
  );
  return encoded.endsWith('/') ? encoded : `${encoded}/`;
};

